const html=E.printHTML(other);
assert.match(html,/試験解体株式会社/);assert.match(html,/試験代表/);
assert.doesNotMatch(html,/16963|宮下|src="toya-document-logo.svg"/,'他社の見積書にTOYAの許可番号・代表者・ロゴを印刷しない');
