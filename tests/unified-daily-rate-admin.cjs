'use strict';
const assert=require('node:assert/strict');
const R=require('../docs/unified-daily-rate-admin.js');
assert.equal(R.dailyToHourly(8000),1000);
assert.equal(R.dailyToHourly(86.4),10.8);
assert.equal(R.dailyToHourly(0),0);
assert(R.validName('新しい重機'));
assert(!R.validName('　'));
assert(!R.validName('A'.repeat(121)));
assert(!R.validName('重機\n別名'));
for(const value of ['',-1,'Infinity',1000000001,0.001])assert(!R.validDaily(value),String(value));
for(const value of [0,'0',86.4,'1000000000'])assert(R.validDaily(value),String(value));
assert.equal(R.norm(' ＳＫ １３５（１号機） '),R.norm('sk135（1号機）'));
const source=require('node:fs').readFileSync(require('node:path').join(__dirname,'../docs/unified-daily-rate-admin.js'),'utf8');
for(const key of ['small_tool_rate_master','equipment_rate_master','vehicle_rate_master'])assert(source.includes(key),key);
assert(source.includes('＋ 品名と単価を追加'));
assert(source.includes('1台・1日あたり（円）'));
assert(source.includes('1台・1時間あたり（自動計算）'));
assert(!source.includes('localStorage'));
console.log('Passed unified daily-rate rules and safety checks.');
