const assert=require('node:assert/strict');
const M=require('../docs/company-monthly-summary.autoselect-r1.js');
const fixture=require('./site-auto-ledger-fixture.cjs');
const bill={id:'sep-progress',site_id:'a',kind:'progress',status:'issued',document_date:'2026-10-08',transaction_start:'2026-09-01',transaction_end:'2026-09-30',subtotal:500000,updated_at:'2026-10-08T00:00:00Z'};
const base=fixture();
base.documents=[bill];
base.profiles=[];
base.contracts=structuredClone(base.revenues).map(r=>({...r,revenue_date:'2026-07-01'}));
const sep=M.calculate(base,'2026-09');
assert.equal(sep.sales,500000,'September claim must follow work month, not issue month');
assert.equal(sep.rows.find(r=>r.site.id==='a').monthlyContractSource,'issued');
assert.equal(sep.rows.find(r=>r.site.id==='a').monthlyContractAmount,500000);
assert.equal(sep.monthlyContractTotal,500000);
assert.equal(sep.monthlyProfit,463700);
const oct=M.calculate(base,'2026-10');
assert.equal(oct.sales,0,'October issue date must not move September work into October');
assert.equal(oct.monthlyContractTotal,null);
const manual=structuredClone(base);
manual.profiles=[{site_id:'a',contract_breakdown:[{target_month:'2026-09',amount:600000,status:'planned'}]}];
const mr=M.calculate(manual,'2026-09');
assert.equal(mr.rows.find(r=>r.site.id==='a').monthlyContractSource,'breakdown');
assert.equal(mr.rows.find(r=>r.site.id==='a').monthlyContractAmount,600000);
assert.equal(mr.monthlyContractTotal,600000,'manual monthly progress replaces, never adds to, issued claim fallback');
assert.equal(mr.monthlyProfit,563700);
const partial=structuredClone(base);
partial.laborSheets.push({id:'extra-cost',site_id:'d',work_date:'2026-09-08',cost_total:50000,revenue_total:0});
const pr=M.calculate(partial,'2026-09');
assert.ok(pr.missingMonthlyContracts>=1);
assert.equal(pr.monthlyContractTotal,500000,'known monthly sales stay visible with another site still missing sales');
assert.equal(pr.monthlyProfit,413700,'provisional profit remains visible and subtracts all known costs');
console.log(JSON.stringify({pass:true,septemberSales:sep.sales,septemberProfit:sep.monthlyProfit,partialProfit:pr.monthlyProfit}));
